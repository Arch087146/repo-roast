/*
 * render.js — output layer: pretty terminal, JSON, markdown export.
 */
"use strict";

const c = (code, s) => `\x1b[${code}m${s}\x1b[0m`;
const bold = (s) => c("1", s);
const dim = (s) => c("2", s);
const red = (s) => c("31", s);
const magenta = (s) => c("35", s);

function terminal(roast, st) {
  console.log();
  console.log(bold(magenta(`  🔥 ROASTING "${st.name}" 🔥`)));
  console.log(dim(`   roastability ${roast.roastability}/100 · tier: ${roast.tier} · ${roast.evidenceCount} findings`));
  console.log();
  for (const line of roast.lines) console.log(`  ${red("→")} ${line}`);
  console.log();
  console.log(bold(`  ${roast.verdict}`));
  console.log();
}

function jsonOut(roast, st) {
  console.log(JSON.stringify({
    repo: st.name,
    roastability: roast.roastability,
    tier: roast.tier,
    verdict: roast.verdict,
    lines: roast.lines,
    evidenceCount: roast.evidenceCount,
  }, null, 2));
}

function markdown(roast, st) {
  const L = [];
  L.push(`# 🔥 Roast of "${st.name}"`);
  L.push("");
  L.push(`> Roastability: **${roast.roastability}/100** · Tier: **${roast.tier}** · ${roast.evidenceCount} findings`);
  L.push("");
  for (const line of roast.lines) L.push(`- ${line}`);
  L.push("");
  L.push(`**${roast.verdict}**`);
  L.push("");
  L.push("<sub>generated by repo-roasted</sub>");
  return L.join("\n");
}

module.exports = { terminal, jsonOut, markdown };
